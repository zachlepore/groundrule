import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

export const DEFAULT_MANIFEST = "research/gis/data/clearwater-sales-v1/demo-properties.json";
const DATASET_ID = "clearwater-sales-v1";
const DESIGNATION = "curated_sales_demo";
const JURISDICTION = "clearwater-fl";
const MUNICIPALITY = "Clearwater";
const ALLOWED_ZONING = new Set(["ldr", "lmdr", "mdr", "mhdr", "hdr", "mhp", "c", "t", "o", "i", "irt", "osr", "p", "d", "us19"]);

const nonempty = (value) => typeof value === "string" && value.trim() === value && value.length > 0;
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const normalizeAddress = (value) => {
  let normalized = ` ${value.trim().replace(/[^A-Z0-9]+/gi, " ").replace(/\s+/g, " ").toUpperCase()} `;
  for (const [long, short] of [["STREET", "ST"], ["ROAD", "RD"], ["AVENUE", "AVE"], ["DRIVE", "DR"], ["PLACE", "PL"], ["PLAZA", "PLZ"], ["COURT", "CT"], ["LANE", "LN"], ["BOULEVARD", "BLVD"], ["HIGHWAY", "HWY"], ["PARKWAY", "PKWY"], ["CIRCLE", "CIR"], ["TERRACE", "TER"]]) normalized = normalized.replaceAll(` ${long} `, ` ${short} `);
  return normalized.trim();
};

export function validateManifest(manifest) {
  const errors = [];
  if (manifest?.schemaVersion !== 1) errors.push("schemaVersion must be 1");
  const dataset = manifest?.dataset ?? {};
  if (dataset.id !== DATASET_ID) errors.push(`dataset.id must be ${DATASET_ID}`);
  if (dataset.designation !== DESIGNATION) errors.push(`dataset.designation must be ${DESIGNATION}`);
  if (dataset.jurisdictionSlug !== JURISDICTION) errors.push(`dataset.jurisdictionSlug must be ${JURISDICTION}`);
  if (dataset.municipality !== MUNICIPALITY) errors.push(`dataset.municipality must be ${MUNICIPALITY}`);
  if (!Array.isArray(manifest?.records)) errors.push("records must be an array");
  const addresses = new Set(), parcels = new Set();
  for (const [index, record] of (manifest?.records ?? []).entries()) {
    const at = `records[${index}]`;
    for (const field of ["displayAddress", "normalizedAddress", "parcelIdentifier", "sourceParcelIdentifier", "zoningCode", "zoningDescription", "normalizedZoningCode", "sourceAddressIdentifier", "ingestBatchId"]) {
      if (!nonempty(record?.[field])) errors.push(`${at}.${field} is required and must be trimmed`);
    }
    if (record?.municipality !== MUNICIPALITY) errors.push(`${at}.municipality must be ${MUNICIPALITY}`);
    if (nonempty(record?.normalizedAddress) && record.normalizedAddress !== normalizeAddress(record.normalizedAddress)) errors.push(`${at}.normalizedAddress must be canonical uppercase address text`);
    if (nonempty(record?.displayAddress) && nonempty(record?.normalizedAddress) && normalizeAddress(record.displayAddress) !== record.normalizedAddress) errors.push(`${at}.displayAddress must normalize to normalizedAddress`);
    if (record?.normalizedZoningCode !== String(record?.normalizedZoningCode ?? "").toLowerCase()) errors.push(`${at}.normalizedZoningCode must be lowercase`);
    if (nonempty(record?.normalizedZoningCode) && !ALLOWED_ZONING.has(record.normalizedZoningCode)) errors.push(`${at}.normalizedZoningCode is not supported by the evaluator`);
    if (nonempty(record?.zoningCode) && nonempty(record?.normalizedZoningCode) && record.zoningCode.toLowerCase().replace(/[\s_-]/g, "") !== record.normalizedZoningCode) errors.push(`${at}.zoningCode does not normalize to normalizedZoningCode`);
    if (record?.verification?.status !== "manually_verified") errors.push(`${at}.verification.status must be manually_verified`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(record?.verification?.verifiedOn ?? "")) errors.push(`${at}.verification.verifiedOn must be YYYY-MM-DD`);
    if (!nonempty(record?.verification?.zoningSource)) errors.push(`${at}.verification.zoningSource is required`);
    if (!nonempty(record?.verification?.zoningMethod)) errors.push(`${at}.verification.zoningMethod is required`);
    if (!nonempty(record?.verification?.jurisdictionSource)) errors.push(`${at}.verification.jurisdictionSource is required`);
    if (!nonempty(record?.verification?.notes)) errors.push(`${at}.verification.notes is required`);
    if (addresses.has(record?.normalizedAddress)) errors.push(`${at}.normalizedAddress duplicates another manifest record`);
    if (parcels.has(record?.parcelIdentifier)) errors.push(`${at}.parcelIdentifier duplicates another manifest record`);
    addresses.add(record?.normalizedAddress); parcels.add(record?.parcelIdentifier);
  }
  if (errors.length) throw new Error(`Invalid Clearwater Sales V1 manifest:\n- ${errors.join("\n- ")}`);
  return manifest;
}

export function renderSql(manifest, manifestPath = DEFAULT_MANIFEST) {
  validateManifest(manifest);
  const statements = [
    "-- Generated by scripts/demo/clearwater-sales-v1.mjs; do not hand-edit.",
    "-- Curated Sales V1 records use the normal canonical property tables and runtime path.",
    "begin;",
    `do $$ begin if not exists (select 1 from public.jurisdictions where slug=${sql(JURISDICTION)} and active) then raise exception 'Active Clearwater jurisdiction is missing'; end if; end $$;`,
  ];
  for (const record of manifest.records) {
    const metadata = JSON.stringify({
      demoDataset: { id: DATASET_ID, designation: DESIGNATION, ingestBatchId: record.ingestBatchId, manifestPath },
      manualVerification: record.verification,
    });
    statements.push(`do $$\nbegin\n  if exists (\n    select 1 from public.property_addresses a join public.jurisdictions j on j.id=a.jurisdiction_id\n    where j.slug=${sql(JURISDICTION)} and a.active and a.normalized_address=public.normalize_property_address(${sql(record.normalizedAddress)})\n  ) then raise exception 'Canonical address already exists: %', ${sql(record.normalizedAddress)}; end if;\n  if exists (\n    select 1 from public.properties p join public.jurisdictions j on j.id=p.jurisdiction_id\n    where j.slug=${sql(JURISDICTION)} and p.parcel_identifier=${sql(record.parcelIdentifier)}\n  ) then raise exception 'Parcel already exists: %', ${sql(record.parcelIdentifier)}; end if;\nend $$;`);
    statements.push(`with inserted_property as (\n  insert into public.properties (jurisdiction_id, parcel_identifier, source_parcel_identifier, zoning_code, zoning_description, normalized_zoning_code, validation_status, source_snapshot_metadata, jurisdiction_key, jurisdiction_authority_name, jurisdiction_source, jurisdiction_source_updated_at, jurisdiction_derived_at)\n  select id, ${sql(record.parcelIdentifier)}, ${sql(record.sourceParcelIdentifier)}, ${sql(record.zoningCode)}, ${sql(record.zoningDescription)}, ${sql(record.normalizedZoningCode)}, 'clean', ${sql(metadata)}::jsonb, 'clearwater', 'City of Clearwater', ${sql(record.verification.jurisdictionSource)}, ${sql(`${record.verification.verifiedOn}T00:00:00Z`)}::timestamptz, ${sql(`${record.verification.verifiedOn}T00:00:00Z`)}::timestamptz\n  from public.jurisdictions where slug=${sql(JURISDICTION)} and active\n  returning id, jurisdiction_id\n)\ninsert into public.property_addresses (property_id, jurisdiction_id, display_address, normalized_address, source_address_identifier, match_method, active)\nselect id, jurisdiction_id, ${sql(record.displayAddress)}, ${sql(record.normalizedAddress)}, ${sql(record.sourceAddressIdentifier)}, 'manual_verification', true from inserted_property;`);
  }
  statements.push("commit;", "");
  return statements.join("\n\n");
}

export function report(manifest) {
  validateManifest(manifest);
  return {
    datasetId: manifest.dataset.id,
    designation: manifest.dataset.designation,
    propertyCount: manifest.records.length,
    zoningDistricts: [...new Set(manifest.records.map((record) => record.normalizedZoningCode))].sort(),
    properties: manifest.records.map((record) => ({ address: record.displayAddress, parcelIdentifier: record.parcelIdentifier, zoningDistrict: record.normalizedZoningCode, verificationStatus: record.verification.status, verifiedOn: record.verification.verifiedOn, ingestBatchId: record.ingestBatchId })),
  };
}

async function main() {
  const [command = "report", manifestPath = DEFAULT_MANIFEST, outputPath, ingestBatchId] = process.argv.slice(2);
  const manifest = validateManifest(JSON.parse(await readFile(manifestPath, "utf8")));
  if (command === "validate") return console.log(`Valid ${DATASET_ID} manifest: ${manifest.records.length} properties`);
  if (command === "report") return console.log(JSON.stringify(report(manifest), null, 2));
  if (command === "sql") {
    if (!outputPath || !ingestBatchId) throw new Error("sql requires an output migration path and ingest batch ID");
    const records = manifest.records.filter((record) => record.ingestBatchId === ingestBatchId);
    if (!records.length) throw new Error(`No records found for ingest batch ${ingestBatchId}`);
    await writeFile(outputPath, renderSql({ ...manifest, records }, manifestPath));
    return console.log(`Wrote ${records.length} properties from ${ingestBatchId} to ${outputPath}`);
  }
  throw new Error("Usage: clearwater-sales-v1.mjs <validate|report|sql> [manifest] [SQL output] [ingest batch ID]");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) main().catch((error) => { console.error(error.message); process.exitCode = 1; });
